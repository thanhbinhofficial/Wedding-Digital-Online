/**
 * Intelligent text translation resolver.
 * Detects standard titles (Groom Ceremony, Bride Ceremony, Reception, etc.) in any stored language
 * and dynamically translates them to the current active language!
 */
export function translateText(
  rawText: string | undefined,
  defaultKey: keyof typeof translations.vi,
  lang: Language
): string {
  const t = getTranslation(lang);
  if (!rawText || rawText.trim() === '') {
    return (t[defaultKey] as string) || '';
  }

  const textLower = rawText.trim().toLowerCase();

  // 1. Groom Ceremony detection
  if (
    defaultKey === 'ceremonyGroom' ||
    textLower.includes('thành hôn') ||
    textLower.includes('nhà trai') ||
    textLower.includes('hằng thuận') ||
    textLower.includes('ជំនូន') ||
    textLower.includes('កាត់សក់') ||
    textLower.includes("groom's") ||
    textLower.includes('groom ceremony')
  ) {
    return t.ceremonyGroom;
  }

  // 2. Bride Ceremony detection
  if (
    defaultKey === 'ceremonyBride' ||
    textLower.includes('vu quy') ||
    textLower.includes('nhà gái') ||
    textLower.includes('đính hôn') ||
    textLower.includes('សំពះផ្ទឹម') ||
    textLower.includes('ចងដៃ') ||
    textLower.includes("bride's") ||
    textLower.includes('bride ceremony')
  ) {
    return t.ceremonyBride;
  }

  // 3. Reception Banquet detection
  if (
    defaultKey === 'receptionTitle' ||
    textLower.includes('tiệc cưới') ||
    textLower.includes('mừng hạnh phúc') ||
    textLower.includes('tiệc rượu') ||
    textLower.includes('ភោជនាហារ') ||
    textLower.includes('reception') ||
    textLower.includes('banquet')
  ) {
    return t.receptionTitle;
  }

  return rawText;
}

